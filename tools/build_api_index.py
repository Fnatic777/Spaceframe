"""build_api_index - list the names exported by the game's App.pyc (SWIG).

App.pyc has no readable source. Its marshal data still holds every SWIG
wrapper name (e.g. "ShipClass_GetTarget"), which this script turns into a
grep-friendly index:  docs/api/App-index.txt, one "Class.Member" per line,
plus "ET_*" event types and other module-level names.
Names only: argument lists must be learned from vanilla .py usage
(grep the game's scripts) and recorded in docs/api/learned.md.

Usage: python tools/build_api_index.py [--game "D:/path"]
"""
import os
import re
import struct
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAME = r"D:\GOG Games\Star Trek Bridge Commander"
IDENT = re.compile(rb"^[A-Za-z_][A-Za-z0-9_]*$")


def marshal_strings(data):
	"""Python 1.5 marshal strings: b's' + int32 little-endian length + bytes."""
	res = set()
	i = 0
	n = len(data)
	while i < n - 5:
		if data[i] == 0x73:  # 's'
			ln = struct.unpack("<i", data[i + 1:i + 5])[0]
			if 0 < ln < 200 and i + 5 + ln <= n:
				s = data[i + 5:i + 5 + ln]
				if IDENT.match(s):
					res.add(s.decode("ascii"))
					i = i + 5 + ln
					continue
		i = i + 1
	return res


def main(argv):
	game = GAME
	if "--game" in argv:
		game = argv[argv.index("--game") + 1]
	data = open(os.path.join(game, "scripts", "App.pyc"), "rb").read()
	names = marshal_strings(data)
	classes = set()
	for s in names:
		if s.endswith("Ptr") and s[:-3] in names:
			classes.add(s[:-3])
	members = set()
	events = set()
	other = set()
	for s in names:
		if s.startswith("ET_"):
			events.add(s)
			continue
		hit = 0
		if "_" in s:
			# longest class prefix wins (e.g. TGUIObject_ vs TGObject_)
			best = ""
			for c in classes:
				if s.startswith(c + "_") and len(c) > len(best):
					best = c
			if best:
				m = s[len(best) + 1:]
				if m and not m.startswith("Ptr"):
					members.add(best + "." + m)
					hit = 1
		if not hit and s[0].isupper() and not s.endswith(("Ptr", "Ptrc")):
			other.add(s)
	# Shadow-class method names ("GetTarget") also appear bare: drop them.
	suffixes = set()
	for m in members:
		suffixes.add(m.split(".", 1)[1])
	other = set([o for o in other if o not in suffixes and o not in classes])
	out_dir = os.path.join(REPO, "docs", "api")
	if not os.path.isdir(out_dir):
		os.makedirs(out_dir)
	path = os.path.join(out_dir, "App-index.txt")
	f = open(path, "w", newline="\n")
	f.write("# Generated by tools/build_api_index.py from scripts/App.pyc - names only, no signatures.\n")
	f.write("# grep -i 'ShipClass\\.Get' docs/api/App-index.txt   |   App.<Class>_Cast(obj) casts a TGObject.\n")
	f.write("# %d classes, %d members, %d event types, %d other names\n" % (len(classes), len(members), len(events), len(other)))
	for c in sorted(classes):
		f.write("class " + c + "\n")
	for m in sorted(members):
		f.write(m + "\n")
	for e in sorted(events):
		f.write("event " + e + "\n")
	for o in sorted(other):
		f.write("name " + o + "\n")
	f.close()
	print("%s: %d classes, %d members, %d events, %d other" % (path, len(classes), len(members), len(events), len(other)))
	return 0


if __name__ == "__main__":
	sys.exit(main(sys.argv[1:]))
